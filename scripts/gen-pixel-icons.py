#!/usr/bin/env python3
"""Turn the pixel-art SVGs into the run lists the clients draw.

Each icon in the set is a 32 x 32 grid of one-pixel-tall rects, one colour
(the "-mono" variant). That is three numbers per rect -- x, y, width -- which
is small enough to compile into the app and lets the deck draw them in
whichever colour the chosen theme uses, rather than the brand's own.

Usage:
  scripts/gen-pixel-icons.py --svg ~/pixel-devtools \
      --out clients/flutter/agents_ui/lib/src/pixel_icons.dart \
      github git terminal vscode notion jira claude
"""

import argparse
import re
import sys
from pathlib import Path

RECT = re.compile(r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"')


def runs(path):
    """The icon as flat x, y, width triples (a rect taller than one pixel is
    split into one run per row, so the drawing code stays a single loop)."""
    out = []
    for x, y, w, h in RECT.findall(path.read_text(encoding="utf-8")):
        x, y, w, h = int(x), int(y), int(w), int(h)
        for row in range(h):
            out.extend((x, y + row, w))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--svg", type=Path, required=True, help="the folder of pixel SVGs")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("names", nargs="+", help="icon names, without the -mono suffix")
    args = ap.parse_args()

    icons = {}
    for name in sorted(set(args.names)):
        p = args.svg / f"{name}-mono.svg"
        if not p.exists():
            print(f"{name}: no {p.name}", file=sys.stderr)
            return 1
        icons[name] = runs(p)

    lines = [
        "// Pixel icons, drawn in the colours of whichever theme is on.",
        "//",
        "// Generated by scripts/gen-pixel-icons.py from the 32 x 32 one-colour",
        "// SVGs of the pixel icon set; do not edit by hand. Each icon is a flat",
        "// list of x, y, width triples: one run of pixels per entry, on a grid",
        "// 32 wide and 32 tall.",
        "",
        "const pixelIconGrid = 32;",
        "",
        "const pixelIcons = <String, List<int>>{",
    ]
    for name, data in icons.items():
        body = ", ".join(str(n) for n in data)
        lines.append(f"  '{name}': [{body}],")
    lines.append("};")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    total = sum(len(v) // 3 for v in icons.values())
    print(f"{len(icons)} icons, {total} runs -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
